export const generateInitialHistory = (): LatencyDataPoint[] => {
  const points: LatencyDataPoint[] = [];
  const now = new Date();
  for (let i = 24; i >= 0; i--) {
    const t = new Date(now.getTime() - i * 60000);
    const timeStr = t.toLocaleTimeString('pt-BR', { hour: '2-digit', minute: '2-digit' });
    const p50 = Math.floor(32 + Math.random() * 8);
    const p95 = Math.floor(75 + Math.random() * 20);
    const p99 = Math.floor(130 + Math.random() * 35);
    const rps = Math.floor(17500 + Math.random() * 2000);
    points.push({ time: timeStr, p50, p95, p99, rps });
  }
  return points;
};
